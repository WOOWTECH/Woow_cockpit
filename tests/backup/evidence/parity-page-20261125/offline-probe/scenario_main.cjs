const assert = require('node:assert/strict');
const { loadBuilders, open } = require('./harness.cjs');
(async () => {
  const b = loadBuilders();
  const page = await open(b, b.v2Fixture({ outcomes: { n8n: { restore: 'rolled-back' } } }));
  const { $, $$, click, tick, until, text } = page;
  await until(() => $(`[data-focus="ha-import-${b.HA_V2}"]`), 'the HA backup row');
  click(`[data-focus="ha-import-${b.HA_V2}"]`);
  await until(() => $('#ha-app-odoo'), 'the apps step');
  tick('#ha-app-hermes', false);
  click('[data-focus="ha-apps-next"]');
  await until(() => $('[data-summary="check"]'), 'the check result', 30000);
  console.log('summary:', text('[data-summary="check"]'));
  console.log('steps:', $$('.stepper .step-label').map(item => item.textContent).join(' > '));
  console.log('emqx importable:', $('[data-ha-app="emqx"]').dataset.importable, '| db radios:', $$('input[name="ha-odoo-database"]').map(i => `${i.value}:${i.disabled ? 'off' : 'on'}:${i.checked ? 'x' : '-'}`).join(' '));
  assert.equal($('[data-focus="ha-import"]').disabled, true);
  tick('#ha-db-0');
  const lines = $$('#ha-confirm-list > li').map(li => `[${li.querySelector('.ha-issue-label')?.textContent}] ${li.querySelector('.ha-issue-text')?.textContent.slice(0, 40)} ${[...li.querySelectorAll('.ha-names li')].map(n => n.textContent).join('|')}`);
  console.log('confirm lines:\n  ' + lines.join('\n  '));
  tick('#ha-ack');
  assert.equal($('[data-focus="ha-import"]').disabled, false);
  tick('#ha-db-1');
  assert.equal($('#ha-ack').checked, false, 'another database untick');
  tick('#ha-db-0');
  tick('#ha-ack');
  click('[data-focus="ha-import"]');
  await until(() => $('[data-result="group"]'), 'the end of the import', 60000);
  console.log('request:', JSON.stringify(page.calls('ha-import-start')[0]).slice(0, 600));
  console.log('result:', text('[data-result="group"] .ha-summary'));
  for (const row of $$('.ha-group-row')) console.log(' row', row.dataset.haApp, row.dataset.status, '|', row.textContent.slice(0, 110));
  console.log('after:', ($('.ha-after') || { textContent: '(none)' }).textContent.slice(0, 200));
  console.log('status live:', text('#status'));
  console.log('fixtureErrors:', JSON.stringify(page.fixtureErrors()), '| page errors:', page.errors.length, page.errors.slice(0, 3).join(' / '));
  page.close();
})().catch(error => { console.error('SCENARIO FAILED:', error.message.slice(0, 2500)); process.exit(1); });
